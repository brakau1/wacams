namespace WACAMS.Core.Interfaces;

/// <summary>
/// Generic repository interface providing CRUD operations for any entity type T.
/// Implementations should use EF Core or another ORM for data persistence.
/// All methods are async and support cancellation via CancellationToken.
/// </summary>
/// <typeparam name="T">The entity type. Must have a Guid Id property.</typeparam>
public interface IRepository<T> where T : class
{
    /// <summary>
    /// Retrieves all records of type T from the database.
    /// Use with caution on large tables — consider pagination in production.
    /// </summary>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>All entities of type T.</returns>
    Task<IEnumerable<T>> GetAllAsync(CancellationToken cancellationToken = default);

    /// <summary>
    /// Retrieves a single record by its surrogate primary key (Guid Id).
    /// </summary>
    /// <param name="id">The GUID primary key of the entity to retrieve.</param>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>The entity if found; null otherwise.</returns>
    Task<T?> GetByIdAsync(Guid id, CancellationToken cancellationToken = default);

    /// <summary>
    /// Inserts a new entity into the database.
    /// The entity's Id is auto-generated by the database.
    /// An AuditLog entry must be created after this operation completes successfully.
    /// </summary>
    /// <param name="entity">The entity to add.</param>
    /// <param name="performedBy">Employee ID of the user performing this action.</param>
    /// <param name="ipAddress">IP address from which the action was initiated.</param>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>The added entity with its generated Id.</returns>
    Task<T> AddAsync(T entity, string performedBy, string? ipAddress = null, CancellationToken cancellationToken = default);

    /// <summary>
    /// Updates an existing entity in the database.
    /// An AuditLog entry capturing old and new values must be created after this operation.
    /// </summary>
    /// <param name="entity">The entity with updated values.</param>
    /// <param name="performedBy">Employee ID of the user performing this action.</param>
    /// <param name="ipAddress">IP address from which the action was initiated.</param>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>The updated entity.</returns>
    Task<T> UpdateAsync(T entity, string performedBy, string? ipAddress = null, CancellationToken cancellationToken = default);

    /// <summary>
    /// Soft-deletes an entity by marking it as deleted.
    /// For hard deletes, set a DeletedAt timestamp to null if soft-delete pattern is used.
    /// An AuditLog entry must be created after this operation.
    /// </summary>
    /// <param name="id">The GUID primary key of the entity to delete.</param>
    /// <param name="performedBy">Employee ID of the user performing this action.</param>
    /// <param name="ipAddress">IP address from which the action was initiated.</param>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>True if the entity was found and deleted; false otherwise.</returns>
    Task<bool> DeleteAsync(Guid id, string performedBy, string? ipAddress = null, CancellationToken cancellationToken = default);

    /// <summary>
    /// Retrieves entities matching a given LINQ expression predicate.
    /// Useful for complex queries beyond simple ID lookups.
    /// </summary>
    /// <param name="predicate">LINQ expression to filter entities.</param>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>All entities matching the predicate.</returns>
    Task<IEnumerable<T>> GetByExpressionAsync(Expression<Func<T, bool>> predicate, CancellationToken cancellationToken = default);

    /// <summary>
    /// Checks whether any entity exists that matches the given predicate.
    /// Efficiently translates to EXISTS query without loading full entities.
    /// </summary>
    /// <param name="predicate">LINQ expression to check existence against.</param>
    /// <param name="cancellationToken">Token to cancel the operation.</param>
    /// <returns>True if at least one matching entity exists; false otherwise.</returns>
    Task<bool> ExistsAsync(Expression<Func<T, bool>> predicate, CancellationToken cancellationToken = default);
}
